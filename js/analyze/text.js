const norm = s => ' ' + s.toLowerCase().replace(/ё/g, 'е').replace(/[^a-zа-я0-9!?.,\s-]/g, ' ').replace(/([!?.,])/g, ' $1 ').replace(/\s+/g, ' ') + ' ';

function findAll(text, stem) {
  // ищем основу в начале слова
  const out = [];
  let i = text.indexOf(stem);
  while (i !== -1) {
    const prev = text[i - 1];
    if (prev === ' ' || prev === undefined || stem.startsWith(' ')) out.push(i);
    i = text.indexOf(stem, i + 1);
  }
  return out;
}
function wordAt(text, i) {
  let s = i, e = i;
  while (s > 0 && text[s - 1] !== ' ') s--;
  while (e < text.length && /[a-zа-я-]/.test(text[e])) e++;
  return text.slice(s, e);
}

export function analyzeText(raw, dateISO) {
  const text = norm(raw);
  const acc = { v: 0, a: 0, t: 0, w: 0, s: 0, n: 0 };
  const hits = [];
  const used = new Set();
  // длинные основы раньше коротких, чтобы «долго разговар» не дублировался «разговар»
  const lex = [...L].sort((x, y) => y[0].length - x[0].length);
  for (const [stem, vec] of lex) {
    for (const i of findAll(text, stem)) {
      if ([...Array(stem.length).keys()].some(k => used.has(i + k))) continue;
      for (let k = 0; k < stem.length; k++) used.add(i + k);
      // отрицание: «не весело», «не холодно»
      const before = text.slice(Math.max(0, i - 4), i);
      const neg = /(^|\s)(не|ни)\s$/.test(before) && !stem.startsWith('не ');
      // усилитель
      const before2 = text.slice(Math.max(0, i - 12), i);
      const k = (/(очень|так|безумно|невероятно|совсем|жутко|ужасно)\s$/.test(before2) ? 1.5 : 1) * (neg ? -0.7 : 1);
      for (const key in vec) acc[key] += vec[key] * (key === 's' || key === 'n' || key === 't' ? Math.abs(k) * (neg ? 0 : 1) : k);
      hits.push({ word: wordAt(text, i), vec, neg });
    }
  }
  const words = text.trim().split(/\s+/).filter(w => /[a-zа-я]/.test(w));
  const excl = (raw.match(/!/g) || []).length;
  const sentences = raw.split(/[.!?…]+/).filter(s => s.trim().length > 2);
  const avgLen = words.length / Math.max(1, sentences.length);
  acc.a += Math.min(excl, 5) * 0.25;
  // длинные плавные предложения — спокойнее, рубленые короткие — резче
  acc.a += avgLen > 16 ? -0.4 : avgLen < 7 ? 0.35 : 0;

  const n = Math.sqrt(hits.length + 1);
  const sq = x => Math.tanh(x / n * 1.2);
  const res = {
    valence: sq(acc.v), arousal: sq(acc.a), tension: Math.min(1, Math.max(0, sq(acc.t))),
    warmth: sq(acc.w), social: Math.min(1, Math.max(0, sq(acc.s) * 1.2)), nostalgia: Math.min(1, Math.max(0, sq(acc.n) * 1.2)),
    words: words.length, sentences: sentences.length, avgLen, exclamations: excl,
    hits: hits.map(h => h.word), hitsDetailed: hits,
  };

  // контекст
  const pick = list => { for (const [stem, ...rest] of list) if (findAll(text, stem).length) return { stem, rest }; return null; };
  const pl = pick(PLACES); res.place = pl ? { loc: pl.rest[0], nom: pl.rest[1], g: pl.rest[2] } : null;
  const ob = [];
  for (const [stem, name] of OBJECTS) { const f = findAll(text, stem); if (f.length && !ob.some(o => o.name === name)) ob.push({ name, at: f[0] }); }
  res.objects = ob.sort((x, y) => x.at - y.at).map(o => o.name);
  const co = pick(COMPANY); res.company = co ? co.rest[0] : null;
  const re = pick(REASONS); res.reason = re ? re.rest[0] : null;
  const has = arr => arr.some(s => findAll(text, s).length);
  res.season = Object.keys(SEASONS).find(k => has(SEASONS[k])) || seasonFromDate(dateISO);
  res.seasonFromText = Object.keys(SEASONS).some(k => has(SEASONS[k]));
  const cnt = arr => arr.reduce((n, st) => n + findAll(text, st).length, 0);
  const tc = ['night', 'evening', 'morning', 'day'].map(k => [k, cnt(TIMES[k])]).filter(x => x[1] > 0);
  res.time = tc.length ? tc.reduce((a, b) => (b[1] > a[1] ? b : a))[0] : null;
  res.weather = Object.keys(WEATHER).filter(k => has(WEATHER[k]));
  res.caption = pickCaption(raw);
  return res;
}

export function seasonFromDate(iso) {
  const m = new Date((iso || new Date().toISOString().slice(0, 10)) + 'T12:00:00').getMonth();
  return m <= 1 || m === 11 ? 'winter' : m <= 4 ? 'spring' : m <= 7 ? 'summer' : 'autumn';
}

// подпись: самое «чувственное» предложение записи
function pickCaption(raw) {
  const sents = raw.replace(/\s+/g, ' ').split(/(?<=[.!?…])\s+/).map(s => s.trim()).filter(Boolean);
  if (!sents.length) return '';
  let best = sents[0], bestScore = -1;
  for (const s of sents) {
    const t = norm(s);
    let sc = 0;
    for (const [stem] of L) if (t.includes(stem)) sc++;
    sc += Math.min(s.length, 110) / 110;
    if (s.length > 140) sc -= 1;
    if (sc > bestScore) { bestScore = sc; best = s; }
  }
  if (best.length > 120) best = best.slice(0, 117).replace(/\s\S*$/, '') + '…';
  return best;
}
