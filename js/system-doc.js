// Страница «Как это работает»: правила визуальной системы — то, что жюри просит объяснить.
import { MODES } from './mood.js';

export function renderSystemDoc() {
  const modes = Object.entries(MODES).map(([k, m]) => `<tr><td><b>${m.name}</b><br><span class="muted">${m.ref}</span></td><td>${m.label}</td><td>${TRIGGER[k]}</td><td>${m.technique}</td><td>${m.why}</td></tr>`).join('');
  return `
  <p class="kicker mono">визуальная система</p>
  <h1>Как настроение дня превращается в форму</h1>
  <p class="lead">Каждая страница дневника — результат правил, а не случайного шаблона. Система читает три входа, сводит их в вектор настроения и по нему выбирает приём, палитру, ритм, движение, фактуру и голос. Любое решение можно объяснить — на странице каждого дня есть блок «Почему этот день выглядит так».</p>

  <h2>1. Формат</h2>
  <p>Вертикальное живое воспоминание <b>9:16 (720×1280)</b>, 15–45 секунд, под музыку дня. Его можно смотреть в дневнике, скачать как видео (.webm) или обложку, а всю папку дня — как .zip.</p>

  <h2>2. Постоянные элементы — то, что делает ленту дневником</h2>
  <ul>
    <li><b>Бумага</b> с волокнами — общий фон, тонированный днём не более чем на 7%.</li>
    <li><b>Сетка</b>: поля 44px, шапка, окно фото, блок названия, подвал — на одних и тех же местах.</li>
    <li><b>Шапка</b>: дата римскими месяцами (<span class="mono">18 · X · 2026</span>), день недели, номер дня <span class="mono">№ 004</span>, штамп настроения.</li>
    <li><b>Шрифты</b>: Cormorant Garamond — название, Caveat — рукописная подпись, JetBrains Mono — служебные строки. Меняется только характер: начертание, курсив, капс, разрядка.</li>
    <li><b>Название = имя папки</b>, 3–7 слов, всегда в одном тоне: «что + где/с кем + деталь».</li>
    <li><b>Рукописная подпись</b> — самое «чувственное» предложение записи, проявляется как будто пишется рукой.</li>
    <li><b>Подпись песни</b> — огибающая громкости трека полосой внизу каждой страницы, с бегущим курсором.</li>
  </ul>

  <h2>3. Переменные элементы</h2>
  <table>
    <tr><th>Элемент</th><th>От чего зависит</th><th>Правило</th></tr>
    <tr><td>Приём обработки фото</td><td>вектор настроения</td><td>6 режимов, см. таблицу ниже; второй по силе режим даёт акценты</td></tr>
    <tr><td>Палитра</td><td>цвета фото + тепло + приятность + лад</td><td>берётся из самих снимков (k-means), затем оттенок сдвигается к охре (тепло) или к синему (холод) на |тепло|·32%, насыщенность × (0.75 + 0.25·приятность + 0.25·энергия − 0.25·ностальгия − 0.12 при миноре)</td></tr>
    <tr><td>Ритм смены кадров</td><td>BPM + энергия</td><td>энергия &gt; 0.45 → 2 доли на кадр; &gt; 0.1 → 4; &gt; −0.35 → 8; ниже → 16. Время кадра = доли × 60 / BPM</td></tr>
    <tr><td>Переход</td><td>приём</td><td>наплыв (Моне, ма) · резкая склейка в сильную долю с глитчем (Кандинский) · цветная шторка (Матисс) · вспышка плёнки · новый фрагмент коллажа</td></tr>
    <tr><td>Воздух вокруг фото</td><td>энергия, лад, темп</td><td>0.25 + 0.45·спокойствие + 0.15 при медленном миноре + 0.35 в режиме «ма»</td></tr>
    <tr><td>Зерно</td><td>ностальгия, эпоха песни</td><td>0.12 + 0.55·ностальгия + 0.15 если песня до 1995 г. + 0.25 в режиме плёнки</td></tr>
    <tr><td>Движение</td><td>энергия, динамика песни</td><td>амплитуда «кен бёрнса», пульса форм; в такт — сильная доля и реальная громкость</td></tr>
    <tr><td>Частицы</td><td>слова о погоде</td><td>«дождь» → дождь, «снег» → снег, «листья» → падающие листья; иначе — пыль в свете (Моне) или конфетти (Матисс)</td></tr>
    <tr><td>Голос озвучки</td><td>вектор настроения</td><td>напряжение → ровный низкий; радость+энергия → быстрый живой; грусть → медленный тихий; ностальгия → рассказчик; покой → тихий тёплый</td></tr>
  </table>

  <h2>4. Художественные приёмы и референсы</h2>
  <table>
    <tr><th>Приём</th><th>Состояние</th><th>Когда включается</th><th>Что делает с фото</th><th>Почему передаёт это ощущение</th></tr>
    ${modes}
  </table>

  <h2>5. Из чего строится вектор настроения</h2>
  <table>
    <tr><th>Вход</th><th>Что извлекается</th><th>Как</th></tr>
    <tr><td>Текст</td><td>приятность, энергия, напряжение, тепло/уют, люди рядом, ностальгия; места, время суток, сезон, погода, детали</td><td>собственный русский словарь (~300 основ) с весами, учётом отрицаний («не весело») и усилителей («очень»); длина фраз и «!» влияют на энергию</td></tr>
    <tr><td>Фото</td><td>доминирующие цвета, свет, контраст, насыщенность, теплота, «цветистость», число кадров</td><td>анализ пикселей в браузере: k-means по 5 цветам, метрика цветистости Хаслера–Зюсструнка</td></tr>
    <tr><td>Музыка (файл)</td><td>темп, энергия, лад и тональность, яркость звука, плотность, динамика, огибающая</td><td>Web Audio: БПФ, spectral flux → автокорреляция → BPM; хромаграмма + профили Крумхансла–Шмуклера → мажор/минор; спектральный центроид → яркость</td></tr>
    <tr><td>Музыка (ссылка)</td><td>жанр, эпоха, характер</td><td>описание песни + словарь жанров и исполнителей, год из текста; встроенный плеер сервиса</td></tr>
  </table>
  <p><b>Сведение:</b> приятность = 0.55·текст + 0.3·музыка + 0.15·фото; энергия = 0.45·текст + 0.4·музыка + 0.15·фото; тепло = 0.45·текст + 0.35·фото + 0.2·музыка. Текст весит больше всего, потому что только он знает, <i>что</i> случилось; музыка — главный источник ритма и энергии; фото — главный источник цвета.</p>

  <h2>6. Глубже, чем «грустно — значит синий»</h2>
  <ul>
    <li>Медленная минорная песня даёт больше воздуха, приглушённые цвета и 8–16 долей на кадр.</li>
    <li>Песня до 1995 года добавляет плёночное зерно, даже если сам день не ностальгический.</li>
    <li>Слово «холодно» рядом с «какао» и «вдвоём» даёт тепло, а не холод: уют перевешивает погоду, и холод остаётся только в частицах.</li>
    <li>Ночная напряжённая работа переворачивает бумагу в тёмную, но сетка, шрифты и подвал остаются теми же — это всё ещё страница того же дневника.</li>
    <li>Палитра всегда начинается с реальных цветов ваших фото, поэтому два «тёплых» дня никогда не совпадут.</li>
  </ul>

  <h2>7. Этика</h2>
  <p>Оценка настроения — художественный приём, а не психологическая диагностика. Записи, фото и песни хранятся только в вашем браузере (IndexedDB) и никуда не отправляются. Демо-дни нарисованы и озвучены процедурно — без чужих фотографий и песен. Голос — синтезированный голос системы.</p>
  `;
}

const TRIGGER = {
  monet: 'приятно + спокойно + тепло, особенно на природе; нет напряжения',
  matisse: 'приятно + энергично, яркие фото',
  kandinsky: 'высокое напряжение (дедлайн, экзамен, стресс), энергия, холод',
  ma: 'неприятно или грустно + спокойно, мало людей, дождь или туман',
  film: 'ностальгия в тексте (детство, бабушка, вспоминали) или старая песня',
  collage: 'много людей + энергия, 3 и больше фото',
};
